"""Pipeline completo S-Log3 -> look de Cris. Un análisis por toma, un .cube por toma (etapas 1-4c), viñeta aparte.

Uso: python -I grade/pipeline.py samples/orig/C0400.MP4 [más tomas] [--solo-frames] [--out samples/graded]
"""
import argparse, json, os, shutil, subprocess, sys
import numpy as np, cv2
sys.path.insert(0, os.path.dirname(__file__))
from etapa1 import *
from etapa2 import estimar, slog3_a_lin, lin_a_slog3, depuracion, guardar, a8
import etapa3, etapa4

N_CUBE = 65


def cargar_luts():
    return (load_cube(buscar_lut("Sony S-Log3 to Rec.709")), load_cube(buscar_lut("Generated by Resolve")))


def cadena(post, P, cfg, lut2):
    """post = salida de la etapa 1 (cualquier forma (...,3)). Aplica etapas 2, 3, 4a, 4b, 4c. Sin viñeta."""
    sh = post.shape
    x = post.reshape(-1, 1, 3).astype(np.float32)
    x = x * np.array(P["ganancias"], np.float32)                                  # 2
    x = etapa3.aplicar_curva(x, np.array(P["curva"])).astype(np.float32)            # 3 (por canal)
    x = etapa4.enfriar(x, cfg["look"]["enfriamiento_t"])                           # 4a
    x = etapa4.creativo(x, lut2, cfg["look"]["intensidad"])                        # 4b
    x = etapa4.hsl_inverso(x, cfg["look"]["hsl_inverso"])                          # 4c
    return np.clip(x, 0, 1).reshape(sh)


def analizar(video, cfg, lut1):
    n = cfg["normalizacion"]
    info = sondear(video)
    dur = float(info["duration"])
    nf = n["frames_por_toma"]
    reps, pcs = [], []
    for i in range(nf):
        t = dur * (i + 0.5) / nf
        src, rango = decodificar_frame(video, t, cfg["entrada"]["rango"], cfg["entrada"]["matriz"], info)
        h, w = src.shape[:2]
        sm = cv2.resize(src, (n["ancho_trabajo"], int(h * n["ancho_trabajo"] / w)), interpolation=cv2.INTER_AREA)
        post = aplicar_lut(sm, lut1)
        r, cand, excl = estimar(post, sm, cfg)
        r["t"] = t
        reps.append((r, post, cand))
    ok = [x for x in reps if x[0]["corregir"]]
    flags = []
    if len(ok) >= max(1, nf // 2 + 1):
        g = np.median([x[0]["ganancias"] for x in ok], axis=0)
        spread = float(np.ptp([x[0]["ganancias"] for x in ok], axis=0).max())
        if spread > 0.08:
            flags.append("ganancias_inestables_entre_frames")
    else:
        g = np.ones(3)
        flags.append("revisar_balance_de_blancos")
    def _pc(post):
        y = post * g
        return etapa3.percentiles(y, (y @ etapa3.LUMA) < n["excluir_sobre"])      # las fuentes de luz no fijan el techo de la curva
    pc = np.median([_pc(x[1]) for x in reps], axis=0)
    curva = etapa3.curva(pc, cfg["luz"])
    P = dict(ganancias=g.tolist(), curva=curva.tolist(), percentiles_base=pc.tolist(),
             percentiles_objetivo=etapa3.objetivos(pc, cfg["luz"]).tolist())
    rep = dict(archivo=video, ffprobe={k: info.get(k) for k in ("width", "height", "pix_fmt", "color_range", "color_space", "color_transfer")},
               rango_usado=rango, banderas=flags, ganancias=g.tolist(),
               frames=[{k: v for k, v in x[0].items() if k in ("t", "n_candidatos", "blanco_estimado", "r_menos_b_blanco", "ganancias", "confianza", "banderas")} for x in reps],
               percentiles_base=pc.tolist(), percentiles_objetivo=P["percentiles_objetivo"])
    return P, rep, reps[len(reps) // 2]


def hornear_cube(path, lut1, P, cfg, lut2, n=N_CUBE):
    t = np.linspace(0, 1, n)
    b, g, r = np.meshgrid(t, t, t, indexing="ij")                    # el rojo varía más rápido
    grid = np.stack([r, g, b], -1)
    out = cadena(aplicar_lut(grid.astype(np.float32), lut1), P, cfg, lut2)
    with open(path, "w") as f:
        f.write(f'TITLE "toma"\nLUT_3D_SIZE {n}\nDOMAIN_MIN 0 0 0\nDOMAIN_MAX 1 1 1\n')
        np.savetxt(f, out.reshape(-1, 3), fmt="%.6f")


def frame_python(src, P, cfg, lut1, lut2):
    """Referencia en Python: etapas 1-4 completas sobre un frame decodificado."""
    y = cadena(aplicar_lut(src, lut1), P, cfg, lut2)
    p = etapa4.mapa_vineta(src.shape[1], src.shape[0], cfg["look"]["vineta"])
    return etapa4.vineta(y, p)


def renderizar(video, cube, cfg, salida):
    info = sondear(video)
    w, h = int(info["width"]), int(info["height"])
    fps = info["r_frame_rate"]
    rango = "full" if (info.get("color_range") in ("pc", None, "unknown") or info["pix_fmt"].startswith("yuvj")) else "limited"
    rin = "pc" if rango == "full" else "tv"
    cdir, cname = os.path.dirname(os.path.abspath(cube)), os.path.basename(cube)
    dec = subprocess.Popen(["ffmpeg", "-v", "error", "-i", os.path.abspath(video), "-vf",
                            f"setparams=range={rin},scale=in_range={rin}:in_color_matrix={cfg['entrada']['matriz']}:out_range=pc,"
                            f"format=gbrp16le,lut3d=file={cname}:interp=tetrahedral,format=rgb48le",
                            "-f", "rawvideo", "-pix_fmt", "rgb48le", "-"], stdout=subprocess.PIPE, cwd=cdir)
    enc = subprocess.Popen(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb48le", "-s", f"{w}x{h}", "-r", fps, "-i", "-",
                            "-vf", "scale=out_range=tv:out_color_matrix=bt709:flags=accurate_rnd+full_chroma_int,format=yuv420p",
                            "-c:v", "libx264", "-crf", "14", "-preset", "medium", "-colorspace", "bt709", "-color_primaries", "bt709",
                            "-color_trc", "bt709", "-color_range", "tv", "-an", salida], stdin=subprocess.PIPE)
    p = etapa4.mapa_vineta(w, h, cfg["look"]["vineta"])
    nbytes = w * h * 6
    k = 0
    while True:
        buf = dec.stdout.read(nbytes)
        if len(buf) < nbytes:
            break
        x = np.frombuffer(buf, np.uint16).reshape(h, w, 3).astype(np.float32) / 65535
        y = etapa4.vineta(x, p)
        enc.stdin.write((np.clip(y, 0, 1) * 65535 + 0.5).astype(np.uint16).tobytes())
        k += 1
    enc.stdin.close(); enc.wait(); dec.wait()
    return k


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("videos", nargs="+")
    ap.add_argument("--out", default=os.path.join(ROOT, "samples", "graded"))
    ap.add_argument("--work", default=os.path.join(ROOT, "out", "pipeline"))
    ap.add_argument("--solo-frames", action="store_true")
    ap.add_argument("--fuerza", type=float, help="sobrescribe normalizacion.fuerza (estilo.yaml)")
    ap.add_argument("--sufijo", default="graded")
    a = ap.parse_args()
    cfg = cargar_config()
    if a.fuerza is not None:
        cfg["normalizacion"]["fuerza"] = a.fuerza
    lut1, lut2 = cargar_luts()
    os.makedirs(a.out, exist_ok=True)
    filas = []
    for v in a.videos:
        nombre = os.path.splitext(os.path.basename(v))[0]
        wd = os.path.join(a.work, a.sufijo, nombre)
        os.makedirs(wd, exist_ok=True)
        P, rep, (r, post_s, cand) = analizar(v, cfg, lut1)
        cube = os.path.join(wd, f"{nombre}.cube")
        hornear_cube(cube, lut1, P, cfg, lut2)
        json.dump(rep, open(os.path.join(wd, "report.json"), "w", encoding="utf-8"), indent=2, ensure_ascii=False)
        info = sondear(v)
        src, _ = decodificar_frame(v, float(info["duration"]) * 0.5, cfg["entrada"]["rango"], cfg["entrada"]["matriz"], info)
        antes = aplicar_lut(src, lut1)
        despues = frame_python(src, P, cfg, lut1, lut2)
        guardar(os.path.join(wd, "antes_etapa1.png"), antes)
        guardar(os.path.join(wd, "despues.png"), despues)
        print(nombre, "banderas", rep["banderas"], "gan", np.round(P["ganancias"], 3),
              "p base", np.round(P["percentiles_base"], 3), "-> obj", np.round(P["percentiles_objetivo"], 3))
        hgt = 360
        f = lambda im: cv2.resize(im, (int(im.shape[1] * hgt / im.shape[0]), hgt), interpolation=cv2.INTER_AREA)
        filas.append(np.hstack([f(antes), f(despues)]))
        if not a.solo_frames:
            salida = os.path.join(a.out, f"{nombre}_{a.sufijo}.mp4")
            n = renderizar(v, cube, cfg, salida)
            print("  ->", salida, n, "frames")
    ancho = max(x.shape[1] for x in filas)
    guardar(os.path.join(a.work, a.sufijo, "contact_sheet.png"), np.vstack([np.pad(x, ((0, 0), (0, ancho - x.shape[1]), (0, 0))) for x in filas]))


if __name__ == "__main__":
    main()
